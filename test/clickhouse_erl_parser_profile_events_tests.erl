-include_lib("eunit/include/eunit.hrl").
-include("clickhouse_erl_protocol.hrl").

hex_to_bin(HexStr) ->
    binary:decode_hex(list_to_binary([C || C <- HexStr, C > $\s])).

parse_stream(Bin) ->
    parse_stream(Bin, ?PROTOCOL_VERSION).

parse_stream(Bin, Version) ->
    State0 = clickhouse_erl_parser:init(Version),
    {AllEvents, _FinalState, _Idx} = lists:foldl(
        fun(Byte, {EventsAcc, AccState, Idx}) ->
            case clickhouse_erl_parser:parse(<<Byte>>, AccState) of
                {error, Reason} ->
                    erlang:error(
                        {parser_failed, Reason, at_byte_val, Byte, at_offset, Idx, state, AccState,
                            acc_events, EventsAcc}
                    );
                {ok, Events, NextState} ->
                    {EventsAcc ++ [E || E <- Events, E =/= need_more], NextState, Idx + 1}
            end
        end,
        {[], State0, 0},
        binary_to_list(Bin)
    ),
    AllEvents.

