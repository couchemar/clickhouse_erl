parse_server_hello_chunked_test() ->
    Msg = """
    00 0a 43 6c 69 63 6b 48 6f 75 73 65 19 0c d3 a9
    03 03 55 54 43 0c 35 39 34 32 63 32 33 65 61 32
    39 61 01
    """,
    BinMsg = hex_to_bin(Msg),
    <<Chunk1:10/binary, Chunk2/binary>> = BinMsg,

    State0 = clickhouse_erl_parser:init(?PROTOCOL_VERSION),
    {ok, Events1, State1} = clickhouse_erl_parser:parse(Chunk1, State0),
    ?assertEqual([{start, server_hello}, need_more], Events1),
    {ok, Events2, _State2} = clickhouse_erl_parser:parse(Chunk2, State1),
    ?assertEqual(
        [
            {data, name, <<"ClickHouse">>},
            {data, version_major, 25},
            {data, version_minor, 12},
            {data, revision, 54483},
            {data, timezone, <<"UTC">>},
            {data, display_name, <<"5942c23ea29a">>},
            {data, version_patch, 1},
            {'end', server_hello},
            need_more
        ],
        Events2
    ),
    AllEvents = [E || E <- Events1 ++ Events2, E =/= need_more],

    ?assertEqual(
        [
            {start, server_hello},
            {data, name, <<"ClickHouse">>},
            {data, version_major, 25},
            {data, version_minor, 12},
            {data, revision, 54483},
            {data, timezone, <<"UTC">>},
            {data, display_name, <<"5942c23ea29a">>},
            {data, version_patch, 1},
            {'end', server_hello}
        ],
        AllEvents
    ).

