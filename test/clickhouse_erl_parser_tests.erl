init_with_version_only_has_no_compression_test() ->
    State = clickhouse_erl_parser:init(?PROTOCOL_VERSION),
    ?assertEqual(undefined, maps:get(compression_opts, State, undefined)).

init_with_compression_opts_stores_them_test() ->
    Opts = #{method => lz4, enabled => true},
    State = clickhouse_erl_parser:init(?PROTOCOL_VERSION, Opts),
    ?assertEqual(Opts, maps:get(compression_opts, State)).

init_with_undefined_compression_opts_test() ->
    State = clickhouse_erl_parser:init(?PROTOCOL_VERSION, undefined),
    ?assertEqual(undefined, maps:get(compression_opts, State)).

init_with_compression_opts_preserves_version_test() ->
    Opts = #{method => zstd, enabled => true},
    State = clickhouse_erl_parser:init(?PROTOCOL_VERSION, Opts),
    ?assertEqual(?PROTOCOL_VERSION, maps:get(version, State)),
    ?assertEqual(initial, maps:get(state, State)),
    ?assertEqual(<<>>, maps:get(buffer, State)).

compression_opts_preserved_across_parse_test() ->
    Opts = #{method => lz4, enabled => true},
    State0 = clickhouse_erl_parser:init(?PROTOCOL_VERSION, Opts),
    %% Parse a PONG packet (type 4) - simplest complete packet
    {ok, _Events, State1} = clickhouse_erl_parser:parse(<<?SERVER_PONG:8>>, State0),
    ?assertEqual(Opts, maps:get(compression_opts, State1)).
